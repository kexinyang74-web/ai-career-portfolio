def remove_duplicates(nums):
    slow = 0
    for fast in range(1, len(nums)):
        if nums[fast] != nums[slow]:
            slow += 1
            nums[slow] = nums[fast]
    return slow + 1

nums = [1,1,2]
print(remove_duplicates(nums))
print(nums)





# 逐行解释（做了什么 + 为什么）
# 角色设定：数组里重复元素挨在一起（因为有序）——所以检查员不需要记住所有见过的元素，只需要和"最后一个留下的"比就行。

# 代码	做了什么	为什么
# class Solution:	答题盒	网站规矩，固定写法
# def removeDuplicates(self, nums):	定义方法	self 是 Python 自动传的"对象自己"，真正用到的参数是 nums
# slow = 0	写字的人坐在 0 号位	0 号元素必然保留（第一个元素不可能重复），slow 记住"最后一个保留者的位置"
# for fast in range(1, len(nums)):	检查员从 1 号位开始看	0 号位已经保留了，不用比；从 1 开始，一个不漏看到最后
# if nums[fast] != nums[slow]:	当前元素 ≠ 上一个保留的？	有序数组重复必相邻：和最后一个保留的比就够，不用和前面所有比（这就是 27 题之后的新知识）
# slow += 1	新元素先"腾座位"	发现新面孔，写字的人先挪到下一个空位
# nums[slow] = nums[fast]	新面孔坐到新位置	覆盖写入，不新建数组（原地）
# return slow + 1	交卷	slow 是"最后一个保留者的索引"，长度 = 索引 + 1
# 用官方例子走一遍（nums = [0,0,1,1,1,2,2,3,3,4]）
# fast 看谁	和 nums[slow] 比	重复？	动作	slow
# 1（值 0）	和 nums[0]=0 比	✅ 重复	跳过	0
# 2（值 1）	和 nums[0]=0 比	❌ 新的	slow=1，nums[1]=1	1
# 3（值 1）	和 nums[1]=1 比	✅ 重复	跳过	1
# 4（值 1）	和 nums[1]=1 比	✅ 重复	跳过	1
# 5（值 2）	和 nums[1]=1 比	❌ 新的	slow=2，nums[2]=2	2
# 6（值 2）	和 nums[2]=2 比	✅ 重复	跳过	2
# 7（值 3）	和 nums[2]=2 比	❌ 新的	slow=3，nums[3]=3	3
# 8（值 3）	重复	跳过		3
# 9（值 4）	❌ 新的	slow=4，nums[4]=4	4	
# 结果：返回 4 + 1 = 5 ✅，数组前 5 位是 [0, 1, 2, 3, 4]。

# 这道题你学到的（对比 27 题）
# 知识点	内容
# 有序数组的福利	有序 → 重复必相邻 → 只和上一个比，O(n) 搞定；如果无序就要用哈希表记录（你 Day 10 学的 set）
# slow 语义又换了	27 题 slow = "下一个空位"（先写后挪）；26 题 slow = "最后一个保留者"（先挪后写）——同一套双指针，语义随题目变，这是你要练的敏锐度
# 边界处理	fast 从 1 开始（0 号必然保留）、return slow + 1（索引 vs 长度）——错一点答案就偏 1
# 复杂度	时间 O(n) 一趟、空间 O(1) 原地
# 一句话：27 题筛"固定值"，26 题筛"邻居"，底层都是快慢指针，变化的是判断条件和 slow 的语义。

