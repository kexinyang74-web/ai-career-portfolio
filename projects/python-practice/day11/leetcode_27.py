nums = [0,1,2,2,3,0,4,2]
val = 2

def remove_element(nums, val):
    slow = 0                          # 写字的人，从 0 号位开始
    for fast in range(len(nums)):     # 检查员挨个看
        if nums[fast] != val:         # 检查员发现：这个不是要移除的！
            nums[slow] = nums[fast]
            slow += 1 # ① 写字的人把它放到 slow 位置
    return slow   # 返回写字的人的位置，即新数组的长度
print(remove_element(nums, val))




# 三、这道题你真正学到的东西（面试常考）
# 知识点	内容
# 双指针思想	一个数组上用两个"手指"干不同的活：fast 负责看（读），slow 负责写。这是算法题最高频的思想之一
# 原地修改	不新建数组，靠覆盖旧值实现——所以额外空间是 O(1)（常数），这就是题目"不要额外空间"的要求
# 为什么不能直接删	Python 的 remove() 每次删除都要搬动后面所有元素，慢；而且循环中删除会让下标错位（你以后会遇到这个经典坑）
# 复杂度分析	每个元素只看一次 → 时间 O(n)；不新建数组 → 空间 O(1)。"遍历一遍、常数空间"就是最优解的标志
# 一句话总结这道题：快慢指针 = 一个"筛选器"，把符合条件的值往前挤，不合适的自然被丢在后面。




# 先记住整段代码的角色设定：数组是一个教室，我们要把"不合格的学生"（等于 val 的）赶出去，但只能原地重新排座位，不能换教室。

# 代码	做了什么	为什么这么做
# class Solution:	建一个"答题盒"	网站的规矩：所有题都装在这个类里
# def removeElement(self, nums, val):	定义方法，收两个参数	self 是类自带的规矩（Python 自动传，你忽略它）
# slow = 0	写字的人从 0 号座位开始	slow 永远指向下一个空座位（要写入的位置）
# for fast in range(len(nums)):	检查员从 0 号座位走到最后一个	保证每个元素都被检查一次，一个不漏
# if nums[fast] != val:	判断：这个学生合格吗？	!= 是"不等于"——只搬运要留下的，等于 val 的当作不存在
# nums[slow] = nums[fast]	合格的坐到 slow 指的空座位	覆盖写入：旧值被新值盖掉，这就是"原地"
# slow += 1	空座位让给下一个	每个合格者坐一个座位，写一个前进一个
# return slow	交卷：新长度	合格者恰好都坐在前 slow 个座位，所以 slow 就是新长度