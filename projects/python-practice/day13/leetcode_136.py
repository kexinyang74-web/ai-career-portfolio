class Solution:                          # 答题盒：网站的固定要求，每道题都这样
    def singleNumber(self, nums: List[int]) -> int:
        # self = 对象自己（Python 自动传的，不用管）
        # nums = 输入的数组，比如 [2, 2, 1]
        # List[int] = 类型注解：nums 是一个"装着整数"的列表（只是说明，不影响运行）
        # -> int = 类型注解：这个函数会返回一个整数

        result = 0                       # 准备一个"累加器"，从 0 开始
        # 为什么从 0 开始？因为 0 异或任何数 = 它本身（a ^ 0 = a），
        # 所以 0 当起点，第一次异或就老老实实把第一个数"记"下来

        for num in nums:                 # 把数组里的数挨个拿出来，叫 num
            # 比如 [2, 2, 1]：第一次 num = 2，第二次 num = 2，第三次 num = 1
            # 每个数都过一遍这个循环，一个不漏

            result = result ^ num        # 核心魔法：把 result 和 num 异或，结果存回 result
            # "累加器"每遇到一个数就碰一次：
            #   第一次：0 ^ 2 = 2（记下 2）
            #   第二次：2 ^ 2 = 0（同一个数又来了，抵消成 0）
            #   第三次：0 ^ 1 = 1（剩下 1）
            # 规律：成对出现的数碰两次就抵消成 0，落单的数永远留在 result 里

        return result                    # 把 result 交出去
        # 循环结束，成对的都抵消光了，result 里就是"只出现一次的数"
        # 数组 [2, 2, 1] → 返回 1

        # 完整过程（跟着写一遍）：
        #   result = 0
        #   0 ^ 2 = 2
        #   2 ^ 2 = 0     ← 两个 2 碰一起，抵消
        #   0 ^ 1 = 1     ← 1 没人配对，幸存
        #   return 1 ✅
