# Day 17 第 1 步：类型注解（练习文件）
# 类型注解 = 给代码写"说明书"：变量: 类型、函数 -> 类型
# 注意：注解不强制检查（写错也不报错），但 VS Code 会帮你划线提醒

# 例子 1：带注解的函数
def add(a: int, b: int) -> int:
    return a + b


# 例子 2：带注解的变量
name: str = "小明"

print(add(1, 2))          # 正常
print(add("a", "b"))      # 不会报错！只是把字符串拼起来了（这就是"注解不强制"的意思）

